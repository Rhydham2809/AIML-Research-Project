    plt.tight_layout(); fig.savefig(RESULT_DIR / f'{run_name}_confusion_matrix.png', dpi=160); plt.show(); plt.close(fig)
    report = classification_report(y_true, y_pred, labels=list(range(NUM_CLASSES)), target_names=class_names,
                                   output_dict=True, zero_division=0)
    pd.DataFrame(report).transpose().to_csv(RESULT_DIR / f'{run_name}_classification_report.csv')
    print('Best validation metrics:', best_metrics)
    print('Saved best checkpoint:', best_path)
    del optimizer, scheduler, criterion, scaler
    if DEVICE.type == 'cuda': torch.cuda.empty_cache()
    return {'run_name': run_name, 'arch': arch, 'loss_type': loss_type,
            **best_metrics, 'checkpoint': str(best_path), 'model': model}

