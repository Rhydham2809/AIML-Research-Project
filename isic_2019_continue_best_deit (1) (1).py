def run_experiment(run_name, arch, loss_type, epochs=EPOCHS):
    print('\n' + '=' * 78)
    print(f'RUN: {run_name} | architecture={arch} | loss={loss_type} | epochs={epochs}')
    model = build_model(arch, NUM_CLASSES)
    if loss_type == 'ce':
        criterion = nn.CrossEntropyLoss()
    elif loss_type == 'cb_focal':
        counts = train_df['label_id'].value_counts().reindex(range(NUM_CLASSES), fill_value=0).to_numpy()
        criterion = ClassBalancedFocalLoss(counts).to(DEVICE)
    else:
        raise ValueError('Unknown loss type: ' + loss_type)

    lr = 2e-4 if arch == 'resnet50' else 1e-4
    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=1e-4)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=epochs)
    use_amp = DEVICE.type == 'cuda'
    scaler = torch.amp.GradScaler('cuda', enabled=use_amp)
    best_f1 = -1.0
    best_path = RESULT_DIR / f'{run_name}_best.pth'
    history = []

    for epoch in range(1, epochs + 1):
        model.train()
        loss_sum, seen = 0.0, 0
        pbar = tqdm(train_loader, desc=f'{run_name} | epoch {epoch}/{epochs}')
        for images, labels in pbar:
            images = images.to(DEVICE, non_blocking=True)
            labels = labels.to(DEVICE, non_blocking=True)
            optimizer.zero_grad(set_to_none=True)
            with torch.amp.autocast(device_type='cuda', enabled=use_amp):
                logits = model(images)
                loss = criterion(logits, labels)
            scaler.scale(loss).backward()
            scaler.step(optimizer)
            scaler.update()
            batch_n = labels.size(0)
            loss_sum += float(loss.detach()) * batch_n
            seen += batch_n
            pbar.set_postfix(train_loss=f'{loss_sum/max(seen,1):.4f}')

        val_metrics, _, _, _ = evaluate(model, val_loader)
        scheduler.step()
        record = {'run_name': run_name, 'epoch': epoch, 'train_loss': loss_sum/max(seen,1), **val_metrics}
        history.append(record)
        print('Epoch results:', {k: round(v, 4) if isinstance(v, (int, float)) and np.isfinite(v) else v for k, v in record.items() if k not in ('run_name',)})

        if val_metrics['macro_f1'] > best_f1:
            best_f1 = val_metrics['macro_f1']
            torch.save({
                'model_state_dict': model.state_dict(),
                'arch': arch,
                'loss_type': loss_type,
                'class_names': class_names,
                'num_classes': NUM_CLASSES,
                'epoch': epoch,
                'metrics': val_metrics,
                'seed': SEED,
            }, best_path)

    pd.DataFrame(history).to_csv(RESULT_DIR / f'{run_name}_history.csv', index=False)
