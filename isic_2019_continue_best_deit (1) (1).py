"""## 5. Define the losses, models, and evaluation metrics

The proposed loss uses class weights based on the effective number of examples, a focal factor to emphasize difficult examples, and mild label smoothing. The baselines use ordinary cross-entropy. All models use pretrained weights and the same input size and data split.
"""

class ClassBalancedFocalLoss(nn.Module):
    def __init__(self, class_counts, beta=0.999, gamma=2.0, label_smoothing=0.05):
        super().__init__()
        counts = torch.tensor(class_counts, dtype=torch.float32).clamp(min=1)
        weights = (1.0 - beta) / (1.0 - torch.pow(torch.tensor(beta), counts))
        weights = weights / weights.mean()  # average weight = 1
        self.register_buffer('class_weights', weights)
        self.gamma = gamma
        self.label_smoothing = label_smoothing
    def forward(self, logits, targets):
        ce = F.cross_entropy(logits, targets, reduction='none', label_smoothing=self.label_smoothing)
        probs = torch.softmax(logits, dim=1)
        p_true = probs.gather(1, targets.unsqueeze(1)).squeeze(1)
        focal_factor = (1.0 - p_true).pow(self.gamma)
        weights = self.class_weights[targets]
        return (weights * focal_factor * ce).mean()


def build_model(arch, num_classes):
    # pretrained=True downloads public ImageNet weights the first time.
    return timm.create_model(arch, pretrained=True, num_classes=num_classes).to(DEVICE)


def compute_metrics(y_true, y_pred, y_prob):
    result = {
        'accuracy': float(accuracy_score(y_true, y_pred)),
        'balanced_accuracy': float(balanced_accuracy_score(y_true, y_pred)),
        'macro_f1': float(f1_score(y_true, y_pred, average='macro', zero_division=0)),
    }
    try:
        result['macro_auc_ovr'] = float(roc_auc_score(y_true, y_prob, multi_class='ovr', average='macro'))
    except Exception as exc:
        result['macro_auc_ovr'] = float('nan')
        print('Could not compute macro AUC:', str(exc)[:180])
    return result


@torch.no_grad()
def evaluate(model, loader):
    model.eval()
    y_true, y_pred, y_prob = [], [], []
    use_amp = DEVICE.type == 'cuda'
    for images, labels in tqdm(loader, desc='Validation', leave=False):
        images = images.to(DEVICE, non_blocking=True)
        labels = labels.to(DEVICE, non_blocking=True)
        with torch.amp.autocast(device_type='cuda', enabled=use_amp):
            logits = model(images)
        probs = torch.softmax(logits.float(), dim=1)
        y_true.extend(labels.cpu().numpy().tolist())
        y_pred.extend(probs.argmax(1).cpu().numpy().tolist())
        y_prob.extend(probs.cpu().numpy().tolist())
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)
    y_prob = np.asarray(y_prob)
    return compute_metrics(y_true, y_pred, y_prob), y_true, y_pred, y_prob

